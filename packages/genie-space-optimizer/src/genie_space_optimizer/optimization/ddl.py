_GENIE_OPT_ITERATIONS_DDL = """\
CREATE TABLE IF NOT EXISTS {catalog}.{schema}.genie_opt_iterations (
    run_id              STRING        NOT NULL COMMENT 'FK to genie_opt_runs.run_id',
    iteration           INT           NOT NULL COMMENT 'Evaluation iteration number (0 = baseline)',
    lever               INT                    COMMENT 'Which lever was applied before this eval (null for baseline)',
    eval_scope          STRING        NOT NULL COMMENT 'full|enrichment',
    timestamp           TIMESTAMP     NOT NULL COMMENT 'When this evaluation completed',
    overall_accuracy    DOUBLE        NOT NULL COMMENT 'Overall accuracy percentage (0-100)',
    total_questions     INT           NOT NULL COMMENT 'Number of benchmark questions evaluated',
    correct_count       INT           NOT NULL COMMENT 'Number of questions that passed all judges',
    scores_json         STRING        NOT NULL COMMENT 'JSON: per-judge scores',
    failures_json       STRING                 COMMENT 'JSON: array of failed question IDs',
    remaining_failures  STRING                 COMMENT 'JSON: array of question IDs still failing',
    thresholds_met      BOOLEAN       NOT NULL COMMENT 'True if all quality thresholds passed',
    rows_json           STRING                 COMMENT 'JSON: per-question evaluation detail rows',
    reflection_json     STRING                 COMMENT 'JSON: adaptive loop reflection entry for this iteration',
    evaluated_count     INT                    COMMENT 'Denominator of overall_accuracy (total_questions minus runtime exclusions; see Bug #2 denominator contract)',
    excluded_count      INT                    COMMENT 'Number of rows removed from the denominator at runtime (ground-truth excluded, both empty, Genie unavailable, temporally stale, etc.)',
    rolled_back         BOOLEAN       DEFAULT false COMMENT 'Tier 1.1: true if this iteration was rolled back by the accept/rollback gate. Readers that represent current state must filter this out (see _get_baseline_and_best_accuracy, promote_best_model, load_latest_full_iteration).',
    rolled_back_at      TIMESTAMP              COMMENT 'Tier 1.1: timestamp of rollback',
    rollback_reason     STRING                 COMMENT 'Tier 1.1: human-readable rollback reason (mirrors genie_opt_patches.rollback_reason)',
    config_json         STRING                 COMMENT 'GSO v2 Phase 4 (D3): JSON of the submitted/local Genie Agent config for THIS iteration (baseline iter 0, patch/eval iterations 1..N). Whitelisted Genie-domain projection (optimizer-internal _* keys dropped).',
    observed_config_json STRING                COMMENT 'Authoritative serialized_space returned by GET include_serialized_space=true after the config was persisted. NULL means the API read-back was unavailable; consumers must not infer external drift from the submitted config alone.',
    is_champion         BOOLEAN       DEFAULT false COMMENT 'GSO v2 Phase 4 (D3): true on the single champion iteration row (the best iteration as chosen by the existing Delta-driven selection in promote_best_model). Marked in Delta only — NO UC model registration.',
    num_needs_review    INT                    COMMENT 'Count of per-question rows whose official assessment is NEEDS_REVIEW (neither GOOD nor BAD).',
    eval_run_id         STRING                 COMMENT 'GSO v2 Phase 6: native Genie benchmark eval-run id for this iteration (from the official EvalRunner). Surfaced so the UI can reference the underlying eval run. NULL on the legacy in-process path.',
    eval_run_status     STRING                 COMMENT 'GSO v2 Phase 6: native eval-run terminal status (e.g. DONE / EVALUATION_FAILED / CANCELLED) for this iteration. NULL on the legacy in-process path.',
    attempt_no          INT                    COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): monotonic display counter for the optimize loop — 0=baseline, 1..N=LLM patch/eval attempts.',
    attempt_mode        STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): baseline or llm_patch.',
    best_accuracy       DOUBLE                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): best full-benchmark accuracy seen so far at the end of this attempt (the champion staircase value).',
    best_config_version_id STRING              COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): serialized config snapshot reference for the current champion.',
    current_hypothesis  STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): JSON of the active patch hypothesis tested in this attempt.',
    do_not_repeat       STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): JSON ARRAY of rejected lever families / strategies the controller will not retry.',
    terminal_reason     STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): TARGET_REACHED | MAX_ATTEMPTS | NO_NEW_HYPOTHESIS | EVAL_INVALID | CONFIG_VALIDATION_FAILED | LOOP_STATE_INVALID | EVAL_BUDGET_EXHAUSTED. Set on the champion row only.',
    decision            STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): per-attempt aggregate decision — accept | reject | continue.',
    decision_reason     STRING                 COMMENT 'GSO v2 Phase 7 (loop-state, arch §7.4): human-readable reason for the decision (e.g. rolled_back (Δacc<0), no_enrichment_candidates).',
    surgical_attempts_used INT                 COMMENT 'GSO v2 Phase 8 (loop-state, arch §7.4): patch/eval attempt budget consumed so far.',
    next_hypothesis     STRING                 COMMENT 'GSO v2 Phase 8 (loop-state, arch §7.4): JSON of the next patch idea the controller chose from the residual failures.',
    target_accuracy     DOUBLE                 COMMENT 'GSO v2 Phase 8 (loop-state, arch §7.4): stop-early target accuracy in force for this run (0-100 scale; default 90.0).',
    max_attempts        INT                    COMMENT 'GSO v2 Phase 8 (loop-state, arch §7.4): patch/eval attempt budget in force for this run (default 3).'
)
USING DELTA
PARTITIONED BY (run_id)
COMMENT 'Evaluation iteration results - scores and failures per eval pass'
TBLPROPERTIES (
    'delta.autoOptimize.optimizeWrite' = 'true',
    'delta.autoOptimize.autoCompact' = 'true',
    'delta.enableChangeDataFeed' = 'true',
    'delta.feature.allowColumnDefaults' = 'supported'
)"""

