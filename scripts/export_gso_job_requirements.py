#!/usr/bin/env python3
"""Generate the GSO job's locked requirements file from uv.lock.

The GSO wheel only pins its direct dependencies, so every serverless job run
re-resolves the transitive tree against the live index. An upstream release
(e.g. huggingface-hub moving to httpx2) can then make the pins unsatisfiable,
and the job fails at library install. This script exports the locked transitive versions so the job
installs exactly what uv.lock resolved.

Packages already installed in the serverless base environment are dropped:
pinning them to our lock version would make pip silently replace base-image
packages (protobuf, grpcio, pyarrow, ...) that Spark Connect depends on. The
base-package snapshot lives next to the output and must be refreshed whenever
the job's environment_version changes.

Reads uv.lock with --frozen only; never re-locks or changes index URLs.

Usage:
    python scripts/export_gso_job_requirements.py          # write the file
    python scripts/export_gso_job_requirements.py --check  # fail on drift
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PACKAGE_DIR = REPO_ROOT / "packages" / "genie-space-optimizer"
OUTPUT_PATH = PACKAGE_DIR / "requirements-job.txt"
BASE_PACKAGES_SNAPSHOT_PATH = PACKAGE_DIR / "serverless-env-v4-base-packages.txt"

HEADER = """\
# Generated by scripts/export_gso_job_requirements.py from uv.lock — do not edit.
# Locked transitive dependencies for the GSO serverless job, minus packages the
# serverless base environment already ships (serverless-env-v4-base-packages.txt).
# Regenerate after any uv.lock change:
#   python scripts/export_gso_job_requirements.py
"""

_NAME_RE = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def normalize_name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_name(line: str) -> str | None:
    stripped = line.strip()
    if not stripped or stripped.startswith(("#", "-")):
        return None
    match = _NAME_RE.match(stripped)
    return normalize_name(match.group(1)) if match else None


def load_base_package_names(path: Path = BASE_PACKAGES_SNAPSHOT_PATH) -> set[str]:
    names: set[str] = set()
    for line in path.read_text().splitlines():
        name = requirement_name(line)
        if name:
            names.add(name)
    return names


def export_locked_requirements() -> list[str]:
    cmd = [
        "uv",
        "export",
        "--frozen",
        "--package",
        "genie-space-optimizer",
        "--no-dev",
        "--no-hashes",
        "--no-emit-project",
        "--no-emit-workspace",
        "--no-header",
        "--no-annotate",
        "--format",
        "requirements-txt",
    ]
    result = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise RuntimeError(f"uv export failed:\n{result.stderr}")
    return [line.strip() for line in result.stdout.splitlines() if requirement_name(line)]


def render(requirements: list[str], base_packages: set[str]) -> str:
    kept = [line for line in requirements if requirement_name(line) not in base_packages]
    return HEADER + "\n".join(kept) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit non-zero if the committed file is stale")
    args = parser.parse_args()

    content = render(export_locked_requirements(), load_base_package_names())
    rel = OUTPUT_PATH.relative_to(REPO_ROOT)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text() != content:
            print(f"{rel} is stale. Run: python scripts/export_gso_job_requirements.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date.")
        return 0

    OUTPUT_PATH.write_text(content)
    print(f"Wrote {rel} ({content.count(chr(10)) - HEADER.count(chr(10))} pins).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
